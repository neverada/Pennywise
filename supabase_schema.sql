create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    currency text not null default 'Rs'
        check (currency in ('Rs', '$', '€', '£', '₹', 'د.إ')),
    created_at timestamptz not null default now()
);

create table if not exists public.goals (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    name text not null,
    target numeric not null check (target > 0),
    saved numeric not null default 0 check (saved >= 0),
    due_date text not null default ''
);

create table if not exists public.transactions (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    txn_date date not null,
    amount numeric not null check (amount > 0),
    kind text not null check (kind in ('Income', 'Expense')),
    category text not null,
    note text not null default '',
    created_at timestamptz not null default now(),
    goal_id bigint references public.goals(id) on delete set null
);

create table if not exists public.budgets (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    month text not null,
    category text not null default 'All spending',
    amount numeric not null check (amount >= 0),
    unique (user_id, month, category)
);

create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    name text not null,
    unique (user_id, name)
);

alter table public.profiles enable row level security;
alter table public.transactions enable row level security;
alter table public.budgets enable row level security;
alter table public.goals enable row level security;
alter table public.categories enable row level security;

drop policy if exists "Users manage their own profile" on public.profiles;
drop policy if exists "Users manage their own transactions" on public.transactions;
drop policy if exists "Users manage their own budgets" on public.budgets;
drop policy if exists "Users manage their own goals" on public.goals;
drop policy if exists "Users manage their own categories" on public.categories;

create policy "Users manage their own profile"
    on public.profiles for all to authenticated
    using (id = (select auth.uid()))
    with check (id = (select auth.uid()));

create policy "Users manage their own transactions"
    on public.transactions for all to authenticated
    using (user_id = (select auth.uid()))
    with check (
        user_id = (select auth.uid())
        and (
            goal_id is null
            or exists (
                select 1
                from public.goals as owned_goal
                where owned_goal.id = transactions.goal_id
                  and owned_goal.user_id = (select auth.uid())
            )
        )
    );

create policy "Users manage their own budgets"
    on public.budgets for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));

create policy "Users manage their own goals"
    on public.goals for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));

create policy "Users manage their own categories"
    on public.categories for all to authenticated
    using (user_id = (select auth.uid()))
    with check (user_id = (select auth.uid()));

grant usage on schema public to authenticated;
grant select, insert, update, delete on
    public.profiles, public.transactions, public.budgets, public.goals, public.categories
    to authenticated;
grant usage, select on sequence
    public.transactions_id_seq, public.budgets_id_seq, public.goals_id_seq, public.categories_id_seq
    to authenticated;

create or replace function public.restore_account_backup(
    p_transactions jsonb,
    p_budgets jsonb,
    p_goals jsonb,
    p_categories jsonb
)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    current_user_id uuid := auth.uid();
    item jsonb;
    old_goal_id text;
    new_goal_id bigint;
    mapped_goal_id bigint;
    goal_id_map jsonb := '{}'::jsonb;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;

    delete from public.transactions where user_id = current_user_id;
    delete from public.budgets where user_id = current_user_id;
    delete from public.goals where user_id = current_user_id;
    delete from public.categories where user_id = current_user_id;

    for item in select value from jsonb_array_elements(coalesce(p_goals, '[]'::jsonb))
    loop
        insert into public.goals (user_id, name, target, saved, due_date)
        values (
            current_user_id,
            item->>'name',
            (item->>'target')::numeric,
            coalesce((item->>'saved')::numeric, 0),
            coalesce(item->>'due_date', '')
        )
        returning id into new_goal_id;

        old_goal_id := item->>'id';
        if old_goal_id is not null then
            goal_id_map := jsonb_set(goal_id_map, array[old_goal_id], to_jsonb(new_goal_id::text), true);
        end if;
    end loop;

    for item in select value from jsonb_array_elements(coalesce(p_transactions, '[]'::jsonb))
    loop
        mapped_goal_id := null;
        old_goal_id := item->>'goal_id';
        if old_goal_id is not null then
            mapped_goal_id := nullif(goal_id_map->>old_goal_id, '')::bigint;
        end if;

        insert into public.transactions
            (user_id, txn_date, amount, kind, category, note, created_at, goal_id)
        values (
            current_user_id,
            (item->>'txn_date')::date,
            (item->>'amount')::numeric,
            item->>'kind',
            item->>'category',
            coalesce(item->>'note', ''),
            coalesce(nullif(item->>'created_at', '')::timestamptz, now()),
            mapped_goal_id
        );
    end loop;

    for item in select value from jsonb_array_elements(coalesce(p_budgets, '[]'::jsonb))
    loop
        insert into public.budgets (user_id, month, category, amount)
        values (
            current_user_id,
            item->>'month',
            coalesce(item->>'category', 'All spending'),
            (item->>'amount')::numeric
        );
    end loop;

    for item in select value from jsonb_array_elements(coalesce(p_categories, '[]'::jsonb))
    loop
        insert into public.categories (user_id, name)
        values (current_user_id, item->>'name');
    end loop;
end;
$$;

revoke all on function public.restore_account_backup(jsonb, jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.restore_account_backup(jsonb, jsonb, jsonb, jsonb) to authenticated;

